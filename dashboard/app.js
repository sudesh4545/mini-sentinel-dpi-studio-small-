const get = (id) => document.getElementById(id);
let report = null;
const fmt = (n) => new Intl.NumberFormat().format(n);
const safe = (value) => value.replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
})[char]);
